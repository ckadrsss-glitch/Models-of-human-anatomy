// Calibrates the parameter sets of every model shown in the film so that the values MEASURED on
// the deformed bone hit the chosen references exactly (Levenberg–Marquardt, finite differences),
// then writes src/states.js. usage: node tools/calibrate.mjs
import fs from 'fs';
import { ceph, ZERO, SCALE } from '../src/morph.js';

function solve(base, keys, targets, { iters = 60, h = 0.05, lambda0 = 1e-2 } = {}) {
  let x = keys.map((k) => base[k] ?? 0);
  const P = (xx) => { const o = { ...base }; keys.forEach((k, i) => (o[k] = xx[i])); return o; };
  const res = (xx) => { const c = ceph(P(xx)); return targets.map(([m, v, w = 1]) => (c[m] - v) * w); };
  let r = res(x), err = r.reduce((a, b) => a + b * b, 0), lambda = lambda0;
  for (let it = 0; it < iters && err > 1e-8; it++) {
    const J = keys.map((_, j) => { const xx = x.slice(); xx[j] += h; const r2 = res(xx); return r2.map((v, i) => (v - r[i]) / h); });
    const n = keys.length, A = Array.from({ length: n }, () => new Array(n).fill(0)), g = new Array(n).fill(0);
    for (let a = 0; a < n; a++) { for (let b = 0; b < n; b++) for (let i = 0; i < r.length; i++) A[a][b] += J[a][i] * J[b][i]; for (let i = 0; i < r.length; i++) g[a] += J[a][i] * r[i]; }
    let improved = false;
    for (let tries = 0; tries < 12 && !improved; tries++) {
      const M = A.map((row, a) => row.map((v, b) => v + (a === b ? lambda * (1 + v) : 0)));
      const dx = gauss(M, g.map((v) => -v));
      const xn = x.map((v, i) => v + dx[i]);
      const rn = res(xn), en = rn.reduce((a, b) => a + b * b, 0);
      if (en < err) { x = xn; r = rn; err = en; lambda = Math.max(lambda / 3, 1e-6); improved = true; } else lambda *= 4;
    }
    if (!improved) break;
  }
  return { P: P(x), err };
}
function gauss(A, b) {
  const n = b.length, M = A.map((r, i) => [...r, b[i]]);
  for (let c = 0; c < n; c++) {
    let p = c; for (let r = c + 1; r < n; r++) if (Math.abs(M[r][c]) > Math.abs(M[p][c])) p = r;
    [M[c], M[p]] = [M[p], M[c]];
    for (let r = 0; r < n; r++) if (r !== c) { const f = M[r][c] / M[c][c]; for (let k = c; k <= n; k++) M[r][k] -= f * M[c][k]; }
  }
  return M.map((r, i) => r[n] / r[i]);
}
const R = (P) => Object.fromEntries(Object.entries(P).map(([k, v]) => [k, +v.toFixed(5)]));
const show = (name, P) => { const c = ceph(P); console.log(name.padEnd(10), ['SN', 'SAr', 'ArGo', 'GoMe', 'SGo', 'NMe', 'ratio', 'saddle', 'articular', 'gonial', 'sum', 'upperGonial', 'lowerGonial', 'pogAP'].map((k) => `${k} ${c[k].toFixed(2)}`).join('  ')); return c; };

console.log('SCALE', SCALE.toFixed(5));
show('source', ZERO);
// 1. reference (normodivergent) configuration
const REF = solve(ZERO, ['sad', 'pcb', 'rot', 'ramus', 'bend', 'body'],
  [['saddle', 123], ['articular', 143], ['gonial', 130], ['GoMe', 71], ['ratio', 63.8], ['SAr', 33.5]]);
console.log('REF err', REF.err.toExponential(2), R(REF.P)); show('REF', REF.P);
// 2. vertical patterns: REF + v·D (rotation, ramus, gonial angle, symphysis, notch), body length keeps Go–Me = 71 mm
const D = { rot: 3.0, ramus: -4.5, bend: 3.2, sym: 3.0 };
const pat = (v, extra = {}) => { const o = { ...REF.P }; for (const k in D) o[k] = (REF.P[k] || 0) + D[k] * v; o.notch = Math.max(0, v) * 1.2; return { ...o, ...extra }; };
function pattern(target) {
  let lo = -3, hi = 3, P;
  for (let i = 0; i < 40; i++) {
    const v = (lo + hi) / 2;
    P = solve(pat(v), ['body'], [['GoMe', 71]], { iters: 20 }).P;
    (ceph(P).ratio > target) ? (lo = v) : (hi = v);
  }
  return solve(pat((lo + hi) / 2), ['body'], [['GoMe', 71]], { iters: 30 }).P;
}
const HYPER = pattern(56), HYPO = pattern(68);
show('HYPER', HYPER); show('HYPO', HYPO);
// 3. saddle-angle demonstration: REF rotated with the posterior cranial base about S (articular & gonial unchanged)
const SAD_LO = solve(REF.P, ['sad'], [['saddle', 118]]).P, SAD_HI = solve(REF.P, ['sad'], [['saddle', 128]]).P;
show('SAD 118', SAD_LO); show('SAD 128', SAD_HI);
// 4. compensation example (model B): saddle 133°, articular 133°, same gonial angle → same sum
const COMP = solve(REF.P, ['sad', 'rot'], [['saddle', 133], ['articular', 133]]).P;
show('COMP', COMP);
// 5. ramus comparison (short / long ramus), everything else as REF
const RAM_S = solve(REF.P, ['ramus'], [['ArGo', ceph(REF.P).ArGo - 6]]).P, RAM_L = solve(REF.P, ['ramus'], [['ArGo', ceph(REF.P).ArGo + 6]]).P;
show('RAMUS-', RAM_S); show('RAMUS+', RAM_L);
const out = { REF: R(REF.P), HYPER: R(HYPER), HYPO: R(HYPO), SAD_LO: R(SAD_LO), SAD_HI: R(SAD_HI), COMP: R(COMP), RAM_S: R(RAM_S), RAM_L: R(RAM_L) };
fs.writeFileSync('src/states.js', '// generated by tools/calibrate.mjs — do not edit by hand\nexport const STATES = ' + JSON.stringify(out, null, 1) + ';\n');
console.log('wrote src/states.js');
