# Extracts the radiographic contours used to construct the Björk–Jarabak landmarks
# from the lateral projection of assets/skull.bin (both sides superimposed, like a
# lateral cephalogram) and writes src/contours.js.
#
#   mandible.post  posterior border of the condylar process and ramus (min z per row)
#   mandible.inf   inferior border of the mandible incl. angle and symphysis (lowest y per column)
#   base.inf       inferior contour of the basi-occiput / sphenoid body (midline slab |x|<6 mm)
#
# The JS morphology model warps the mandibular contour points with the same
# function that deforms the mesh, so Ar, Go and Me are reconstructed on the
# deformed bone for every frame.          usage: python3 tools/contours.py
import json, numpy as np
from PIL import Image, ImageDraw
H = json.load(open("assets/skull.json")); raw = open("assets/skull.bin", "rb").read()
def ch(n):
    c = next(c for c in H["chunks"] if c["name"] == n)
    return np.frombuffer(raw[c["offset"]:c["offset"] + c["bytes"]], dtype=c["dtype"]).reshape(c["shape"])
P = ch("position"); idx = ch("index").reshape(-1, 3)
ob = {o[0]: o for o in H["objects"]}
def rng(n): _, _, b, nv = ob[n]; return b, b + nv
K = 8.0                                   # px per mm
Z0, Z1, Y0, Y1 = -40.0, 110.0, -115.0, 30.0
W, Hh = int((Z1 - Z0) * K), int((Y1 - Y0) * K)
def mask(names, xmax=None):
    m = Image.new("L", (W, Hh), 0); d = ImageDraw.Draw(m)
    sel = np.zeros(len(P), bool)
    for n in names: a, b = rng(n); sel[a:b] = True
    tri = idx[sel[idx[:, 0]]]
    if xmax is not None: tri = tri[np.abs(P[tri].mean(1)[:, 0]) < xmax]
    for t in tri:
        d.polygon([((P[i, 2] - Z0) * K, (Y1 - P[i, 1]) * K) for i in t], fill=255)
    return np.array(m) > 0
zc = lambda col: Z0 + (col + 0.5) / K
yc = lambda row: Y1 - (row + 0.5) / K
M = mask(["Mandible"])
rows = np.where(M.any(1))[0]; top = rows.min()
post = []
for r in range(top, rows.max() + 1, 4):                 # every 0.5 mm
    c = np.where(M[r])[0]
    if len(c): post.append([float(round(zc(c.min()), 2)), float(round(yc(r), 2))])
inf = []
cols = np.where(M.any(0))[0]
for c in range(cols.min(), cols.max() + 1, 4):
    r = np.where(M[:, c])[0]
    if len(r): inf.append([float(round(zc(c), 2)), float(round(yc(r.max()), 2))])
# anterior border of the symphysis (max z per row below the incisor alveolus) — for pogonion / chin projection
ant = []
for r in range(int((Y1 - (-80.0)) * K), rows.max() + 1, 4):
    c = np.where(M[r])[0]
    c = c[zc(c) > 55] if len(c) else c
    if len(c): ant.append([float(round(zc(c.max()), 2)), float(round(yc(r), 2))])
B = mask(["Occipital bone", "Sphenoid bone"], xmax=6)
base = []
for c in range(int((-14 - Z0) * K), int((26 - Z0) * K), 4):
    r = np.where(B[:, c])[0]
    r = r[yc(r) < -10] if len(r) else r
    if len(r): base.append([float(round(zc(c), 2)), float(round(yc(r.max()), 2))])
out = {"note": "lateral-projection contours, mm (z anterior, y up); see tools/contours.py",
       "condylion": [float(round(zc(np.where(M[top])[0].mean()), 2)), float(round(yc(top), 2))],
       "mandible": {"post": post, "inf": inf, "ant": ant}, "base": {"inf": base}}
open("src/contours.js", "w").write("// generated by tools/contours.py — do not edit\nexport const CONTOURS = " + json.dumps(out, separators=(",", ":"), default=float) + ";\n")
print("post", len(post), "inf", len(inf), "base", len(base), "condylion", out["condylion"])
print("base", base[::4])
print("post", post[::10])
