  s.tongueUp = track([[0, 1], [32.2, 1], [34.0, -0.85], [37.2, -0.85], [38.4, 1], [40.8, 1], [42.2, -1], [44.4, -1], [45.4, 1], [47.0, 1], [47.9, -1], [49.0, -1], [49.6, 1]], t);
